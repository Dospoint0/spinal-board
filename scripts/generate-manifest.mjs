#!/usr/bin/env node
/**
 * Generates src/manifest.js from the folders under the content root.
 *
 * This is the BUNDLED FALLBACK manifest used when the app is served without
 * the dev server's dynamic /api/manifest endpoint (e.g. plain static hosting
 * or a packaged Wallpaper Engine wallpaper). When running under
 * scripts/serve.mjs the app instead fetches /api/manifest, which scans the
 * content root on every request — so newly added folders appear without
 * re-running this script.
 *
 * Usage: node scripts/generate-manifest.mjs
 * Re-run after adding/removing character folders if you ship the fallback.
 * Honors LWPG_CONTENT like scripts/serve.mjs.
 */
import { writeFileSync } from "node:fs";
import { join, normalize } from "node:path";
import { fileURLToPath } from "node:url";
import { scanContentRoot } from "./scan-assets.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const CONTENT_DIR = process.env.LWPG_CONTENT
  ? normalize(join(ROOT, process.env.LWPG_CONTENT))
  : join(ROOT, "content");
const OUT = new URL("../src/manifest.js", import.meta.url).pathname;

const { characters, warnings } = scanContentRoot(CONTENT_DIR);

const src = `/**
 * Generated by scripts/generate-manifest.mjs — DO NOT EDIT BY HAND.
 * The app prefers the dev server's dynamic /api/manifest; this file is the
 * bundled fallback for static deployments. Re-run "node scripts/generate-manifest.mjs"
 * after adding character folders if you ship this fallback.
 *
 * ${characters.length} characters, ${warnings.length} warning(s).
 */

export const CHARACTERS = ${JSON.stringify(characters, null, 2)};

/** Preferred animation when a skeleton has many; falls back to any name
 *  containing "idle", then the first animation. */
export const DEFAULT_ANIMATION_PREFERENCE = ["idle"];
`;

writeFileSync(OUT, src);
console.log(`Wrote ${OUT}: ${characters.length} characters`);
for (const w of warnings) console.warn("  !", w);
